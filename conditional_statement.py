marks = int(input("Enter your marks  : "))

if marks >= 95:
    print("grade A++")
    
elif marks >= 90:
    print("grade A+")
    
elif marks >= 80:
    print("grade A")
    
elif marks >= 70:
    print("grade B")
    
elif marks >= 60:
    print("grade C")
    
elif marks >= 50:
    print("grade D")
    
elif marks >= 40:
    print("grade E")
    
else:
    print("Grade: F (Fail)")
